"""
Reproduce the v1 generator audit.

Prints the root-count distribution produced by the v1 suite's own network
generator, alongside the same statistic from the new sampler at a range of
edge densities. Run from the project root:

    python archive/audit_v1.py

Nothing here is tuned toward any counterexample. The v1 code path below is
copied verbatim from archive/v1_suite.py (the body of `random_network`'s
inner `random_scm`); the new path calls harness.generators unchanged.
"""

from __future__ import annotations

import collections
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from harness.generators import SCMSpace, describe, sample_scm


def v1_root_counts(draws: int = 3000, n: int = 4, seed: int = 0) -> collections.Counter:
    """The v1 generator's coefficient matrix, verbatim, counting root variables."""
    rng = np.random.default_rng(seed)
    counts: collections.Counter = collections.Counter()
    for _ in range(draws):
        C = np.tril(rng.normal(size=(n, n)) * 0.6, k=-1)   # verbatim from v1_suite.py
        C[C == 0] = 0.0
        counts[int((np.abs(C).sum(axis=1) == 0).sum())] += 1
    return counts


def new_root_counts(edge_prob: float, draws: int = 3000, seed: int = 0) -> collections.Counter:
    rng = np.random.default_rng(seed)
    space = SCMSpace(n_vars=(4, 4), edge_prob=edge_prob)
    counts: collections.Counter = collections.Counter()
    for _ in range(draws):
        counts[describe(sample_scm(rng, space)).n_roots] += 1
    return counts


def _fmt(counts: collections.Counter, draws: int) -> str:
    multi = sum(v for k, v in counts.items() if k >= 2)
    spread = ", ".join(f"{k} root{'s' if k != 1 else ''}: {v}" for k, v in sorted(counts.items()))
    return f"{multi / draws * 100:5.1f}%   ({spread})"


def write_macros(draws: int, counts: collections.Counter, path: str) -> None:
    """The two numbers the paper quotes about the v1 generator, so neither is
    typed by hand. The claim is specifically that the suite could not have
    found the failure, and that rests on these counts."""
    one_root = counts.get(1, 0)
    lines = [
        "% Generated by archive/audit_v1.py. Do not edit by hand.",
        f"\\newcommand{{\\VoneDraws}}{{{draws:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\VoneOneRoot}}{{{one_root:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\VoneMultiRoot}}{{{draws - one_root}}}",
        "\\newcommand{\\VoneTests}{18}",
    ]
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")


def main() -> None:
    draws = 3000
    print(f"Root-variable counts over {draws} draws, 4-variable models.\n")
    print(f"{'generator':<34}{'2+ roots':>9}   distribution")
    print("-" * 78)
    v1 = v1_root_counts(draws)
    print(f"{'v1 suite (np.tril, every edge)':<34}{_fmt(v1, draws)}")
    write_macros(draws, v1, os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "paper", "v1_numbers.tex"))
    for p in (1.0, 0.8, 0.6, 0.5, 0.3):
        label = f"harness, edge_prob = {p:.2f}"
        print(f"{label:<34}{_fmt(new_root_counts(p, draws), draws)}")
    print()
    print("Two root variables is the class on which closure under convex")
    print("combination fails. The v1 generator cannot produce it. Definition 1")
    print("of the framework says 'a DAG', not 'a complete DAG'.")


if __name__ == "__main__":
    main()
