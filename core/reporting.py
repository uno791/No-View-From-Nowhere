"""Helpers that write experiment output to disk.

Every number quoted in the report is written by the code into
results/numbers.tex as a LaTeX macro. The report reads that file, so a
number in the PDF cannot differ from the number the code produced.
"""
from __future__ import annotations

import json
import os
import re

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Three destinations, one rule each, so nothing is ever copied by hand:
#   results/     machine-readable record of a run
#   paper/       the LaTeX macro files the document inputs directly
#   paper/figs/  the figures the document includes directly
# Writing the macros into paper/ rather than results/ removes a copy step that
# could leave the document reading numbers from an earlier run.
RESULTS_DIR = os.path.join(_ROOT, "results")
MACROS_DIR = os.path.join(_ROOT, "paper")
FIGURES_DIR = os.path.join(_ROOT, "paper", "figs")


def fmt(value: float, digits: int = 4) -> str:
    """Format a number for LaTeX. Small values use scientific notation."""
    if value == 0:
        return "0"
    if abs(value) < 1e-3 or abs(value) >= 1e5:
        mantissa, exponent = f"{value:.2e}".split("e")
        return f"{mantissa}\\times 10^{{{int(exponent)}}}"
    return f"{value:.{digits}f}"


def save(rq: str, results: dict, macros: dict):
    os.makedirs(RESULTS_DIR, exist_ok=True)
    os.makedirs(MACROS_DIR, exist_ok=True)
    os.makedirs(FIGURES_DIR, exist_ok=True)
    with open(os.path.join(RESULTS_DIR, f"{rq}.json"), "w") as fh:
        json.dump(results, fh, indent=2)
    lines = []
    for name, value in macros.items():
        if not re.fullmatch(r"[A-Za-z]+", name):
            raise ValueError(f"LaTeX macro names may only contain letters: {name}")
        text = value if isinstance(value, str) else fmt(value)
        lines.append(f"\\newcommand{{\\{name}}}{{{text}}}")
    with open(os.path.join(MACROS_DIR, f"{rq}_numbers.tex"), "w") as fh:
        fh.write("% Generated by the code. Do not edit by hand.\n" + "\n".join(lines) + "\n")
